// Pre-renders the receipt fonts into 1-bit glyph bitmaps (src/lib/printing/receiptFonts.generated.ts).
// The iPad draws receipts from these bitmaps, so the receipt font needs no native code and works
// offline. Run again after changing a font or size: `npm run receipt-fonts`.
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { createCanvas, GlobalFonts } from '@napi-rs/canvas';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

// Sizes are in printer dots (8 dots = 1mm on an 80mm printer).
const FONTS = [
  { name: 'small', file: 'Poppins-Regular.ttf', size: 22 },
  { name: 'body', file: 'Poppins-Regular.ttf', size: 26 },
  { name: 'bodyBold', file: 'Poppins-SemiBold.ttf', size: 26 },
  { name: 'large', file: 'Poppins-Bold.ttf', size: 36 },
  { name: 'huge', file: 'Poppins-Bold.ttf', size: 58 },
];

const CHARACTERS = [...Array.from({ length: 95 }, (_, index) => String.fromCharCode(32 + index)), '×', '•', '–'];

// Slightly below half coverage, so thin strokes survive on thermal paper.
const INK_THRESHOLD = 110;

function renderFont({ file, size }, family) {
  GlobalFonts.registerFromPath(join(root, 'assets/fonts', file), family);
  const pad = Math.ceil(size / 2);
  const canvas = createCanvas(size * 3, size * 3);
  const context = canvas.getContext('2d');
  context.font = `${size}px ${family}`;
  const metrics = context.measureText('Hg');
  const ascent = Math.ceil(metrics.fontBoundingBoxAscent);
  const descent = Math.ceil(metrics.fontBoundingBoxDescent);

  const index = [];
  const bytes = [];
  for (const character of CHARACTERS) {
    context.clearRect(0, 0, canvas.width, canvas.height);
    context.fillText(character, pad, pad + ascent);
    const pixels = context.getImageData(0, 0, canvas.width, canvas.height).data;
    const ink = (x, y) => pixels[(y * canvas.width + x) * 4 + 3] >= INK_THRESHOLD;

    let left = canvas.width, right = -1, top = canvas.height, bottom = -1;
    for (let y = 0; y < canvas.height; y++) {
      for (let x = 0; x < canvas.width; x++) {
        if (ink(x, y)) {
          left = Math.min(left, x);
          right = Math.max(right, x);
          top = Math.min(top, y);
          bottom = Math.max(bottom, y);
        }
      }
    }

    const advance = Math.round(context.measureText(character).width * 100);
    if (right < 0) {
      index.push([character.charCodeAt(0), advance, 0, 0, 0, 0, bytes.length]);
      continue;
    }

    const width = right - left + 1;
    const height = bottom - top + 1;
    const bytesPerRow = Math.ceil(width / 8);
    const offset = bytes.length;
    for (let y = 0; y < height; y++) {
      const row = new Array(bytesPerRow).fill(0);
      for (let x = 0; x < width; x++) {
        if (ink(left + x, top + y)) {
          row[x >> 3] |= 0x80 >> (x & 7);
        }
      }
      bytes.push(...row);
    }

    // x/y offsets are from the pen position and the top of the line.
    index.push([character.charCodeAt(0), advance, left - pad, top - pad, width, height, offset]);
  }

  return { ascent, lineHeight: ascent + descent, index, data: Buffer.from(bytes).toString('base64') };
}

const entries = FONTS.map((font, position) => {
  const rendered = renderFont(font, `ReceiptFont${position}`);
  console.log(`${font.name}: ${font.file} ${font.size}px, line ${rendered.lineHeight} dots, ${Math.round(rendered.data.length / 1024)} KB`);
  return `  ${font.name}: {\n    lineHeight: ${rendered.lineHeight},\n    ascent: ${rendered.ascent},\n    index: ${JSON.stringify(rendered.index)},\n    data: '${rendered.data}',\n  },`;
});

writeFileSync(
  join(root, 'src/lib/printing/receiptFonts.generated.ts'),
  `// Generated by tools/receipt-fonts.mjs from assets/fonts (Poppins, SIL Open Font License). Do not edit by hand.\n` +
    `// index rows: [char code, advance x100, x offset, y offset, width, height, byte offset]\n` +
    `import type { BitmapFont } from './raster';\n\n` +
    `export const RECEIPT_FONTS: Record<'${FONTS.map((font) => font.name).join("' | '")}', BitmapFont> = {\n${entries.join('\n')}\n};\n`,
);
