// Converts the receipt logos into 1-bit raster images that the thermal printer prints with GS v 0.
// The result is bundled into the app (src/lib/printing/receiptImages.generated.ts), so logos print
// with no internet and no server. Run again after changing a logo: `npm run receipt-images`.
//
// The logo files are white artwork on a transparent background, so the shape (alpha) becomes ink:
// anything opaque prints black on the white paper.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { PNG } from 'pngjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

// widthDots is the printed width; an 80mm printer prints 576 dots (72mm) across.
const IMAGES = [
  { name: 'headerLogo', file: 'assets/logo primary.png', widthDots: 264 },
  { name: 'footerArt', file: 'assets/Logo secondary.png', widthDots: 128 },
];

const INK_THRESHOLD = 0.45;

function convert({ file, widthDots }) {
  const png = PNG.sync.read(readFileSync(join(root, file)));
  const alpha = (x, y) => png.data[(y * png.width + x) * 4 + 3] / 255;

  // Crop the transparent margin so widthDots is the width of the artwork itself.
  let left = png.width, right = -1, top = png.height, bottom = -1;
  for (let y = 0; y < png.height; y++) {
    for (let x = 0; x < png.width; x++) {
      if (alpha(x, y) >= INK_THRESHOLD) {
        left = Math.min(left, x);
        right = Math.max(right, x);
        top = Math.min(top, y);
        bottom = Math.max(bottom, y);
      }
    }
  }

  if (right < 0) {
    throw new Error(`${file} has no visible pixels.`);
  }

  const cropWidth = right - left + 1;
  const cropHeight = bottom - top + 1;
  const width = Math.ceil(widthDots / 8) * 8;
  const scale = cropWidth / width;
  const height = Math.round(cropHeight / scale);

  // Bilinear sampling smooths the edges when a small logo is scaled up to printer resolution.
  const sample = (sx, sy) => {
    const x0 = Math.max(0, Math.min(cropWidth - 1, Math.floor(sx)));
    const y0 = Math.max(0, Math.min(cropHeight - 1, Math.floor(sy)));
    const x1 = Math.min(cropWidth - 1, x0 + 1);
    const y1 = Math.min(cropHeight - 1, y0 + 1);
    const fx = Math.max(0, Math.min(1, sx - x0));
    const fy = Math.max(0, Math.min(1, sy - y0));
    const at = (x, y) => alpha(left + x, top + y);
    return (at(x0, y0) * (1 - fx) + at(x1, y0) * fx) * (1 - fy) + (at(x0, y1) * (1 - fx) + at(x1, y1) * fx) * fy;
  };

  // Shrinking averages every source pixel under the dot, so thin lines fade to grey instead of
  // vanishing between samples; the max with the centre sample keeps them printing.
  const coverage = (x, y) => {
    const center = sample((x + 0.5) * scale - 0.5, (y + 0.5) * scale - 0.5);
    if (scale <= 1) {
      return center;
    }

    let total = 0;
    let count = 0;
    for (let sy = Math.floor(y * scale); sy < Math.ceil((y + 1) * scale); sy++) {
      for (let sx = Math.floor(x * scale); sx < Math.ceil((x + 1) * scale); sx++) {
        total += alpha(left + Math.min(cropWidth - 1, sx), top + Math.min(cropHeight - 1, sy));
        count++;
      }
    }

    return Math.max(center, (total / count) * 1.6);
  };

  const bytesPerRow = width / 8;
  const data = Buffer.alloc(bytesPerRow * height);
  for (let y = 0; y < height; y++) {
    for (let x = 0; x < width; x++) {
      if (coverage(x, y) >= INK_THRESHOLD) {
        data[y * bytesPerRow + (x >> 3)] |= 0x80 >> (x & 7);
      }
    }
  }

  return { width, height, data: data.toString('base64') };
}

const entries = IMAGES.map((image) => {
  const raster = convert(image);
  console.log(`${image.name}: ${image.file} -> ${raster.width}x${raster.height} dots`);
  return `  ${image.name}: {\n    width: ${raster.width},\n    height: ${raster.height},\n    data: '${raster.data}',\n  },`;
});

writeFileSync(
  join(root, 'src/lib/printing/receiptImages.generated.ts'),
  `// Generated by tools/receipt-images.mjs from the logos in assets/. Do not edit by hand.\n` +
    `import type { RasterImage } from './raster';\n\n` +
    `export const RECEIPT_IMAGES: Record<'${IMAGES.map((image) => image.name).join("' | '")}', RasterImage> = {\n${entries.join('\n')}\n};\n`,
);
